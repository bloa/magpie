import re


def color_diff(diff):
    out = diff[:]
    for patt, repl in [
            (r'^(\*\*\*\*.*)$', r'\033[36m\1\033[0m'),
            (r'^(--- .* ----)$', r'\033[36m\1\033[0m'),
            (r'^(\*\*\* .* \*\*\*\*)$', r'\033[36m\1\033[0m'),
            (r'^((?:---|\+\+\+|\*\*\*) .*)$', r'\033[1m\1\033[0m'),
            (r'^(-.*)$', r'\033[31m\1\033[0m'),
            (r'^(\+.*)$', r'\033[32m\1\033[0m'),
            (r'^(!.*)$', r'\033[33m\1\033[0m'),
            (r'^(@@ .* @@)', r'\033[36m\1\033[0m'),
    ]:
        out = re.sub(patt, repl, out, flags=re.MULTILINE)
    return out
